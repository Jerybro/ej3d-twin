def write(dwg: str, rows: list) -> None:
    out = {
        "drawing": dwg, "plant": PLANT,
        "source": "圖面右上角設備清單表，Claude 視覺判讀逐列謄錄",
        "verified_by": None, "verified_at": None,
        "items": [
            {"item": i, "range": r, "name": n, "spec": s,
             "driver": d, "qty": q, "remark": rm, "vfd": "變頻" in rm}
            for i, r, n, s, d, q, rm in rows
        ],
    }
    dst = Path(__file__).resolve().parent.parent / "data" / "pid_registry"
    dst.mkdir(parents=True, exist_ok=True)
    p = dst / f"{dwg}.json"
    p.write_text(json.dumps(out, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"{dwg[:28]}… → {len(rows)} 列"
          f"（變頻 {sum(1 for x in out['items'] if x['vfd'])}）")


